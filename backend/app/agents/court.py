"""AI Agent Court: Red Team challenges and evidence-based responses.

Objections are generated by explicit challenge rules over the structured findings and
simulation outputs (not free text). Each rule names the target finding, the objection type,
and computes the counter-evidence. Responses are produced by the challenged agent using the
mitigations available in the model; the resolution status records whether the objection was
answered with evidence (resolved), partially mitigated, or left open (unresolved).
"""

from __future__ import annotations

from .base import AgentContext, Finding, Objection, m
from .domain import _fa, _fe


def _find(findings: list[Finding], code: str) -> Finding | None:
    return next((f for f in findings if f.code == code), None)


def redteam_challenge(ctx: AgentContext, findings: list[Finding]) -> list[Objection]:
    obs: list[Objection] = []
    sim = ctx.simulation
    assert sim is not None
    acc = ctx.controls.acceptable_delay_increase_pct

    # R1: optimistic contractor-absorption assumption behind the highest-savings future
    best = max("ABC", key=lambda k: sim["futures"][k]["summary"]["savings_pct_at_deadline"]["p50"])
    sens = {s["parameter"]: s for s in sim["futures"][best]["sensitivity"]}
    sm = sens.get("skill_match")
    if sm and sim["futures"][best]["levers"]["contractor_reduction"] > 0:
        obs.append(Objection(
            "redteam", "cfo", f"CFO-F{best}", best, "unsupported_assumption", "high",
            f"The CFO's case for {_fe(best)} assumes internal employees can absorb contractor work (skill match 55%). "
            f"This is unsupported — no skills inventory exists. At the low end (35%) delay rises to "
            f"+{sm['delay_at_low']:.1f} pts and net benefit falls to EGP {m(sm['net_benefit_at_low'])}M.",
            f"حجة المدير المالي لصالح {_fa(best)} تفترض قدرة الموظفين على استيعاب أعمال المتعاقدين (توافق مهارات 55%). "
            f"هذا غير مدعوم — لا يوجد سجل مهارات. عند الحد الأدنى (35%) يرتفع التأخير إلى +{sm['delay_at_low']:.1f} نقطة "
            f"وينخفض صافي المنفعة إلى {m(sm['net_benefit_at_low'])} مليون.",
        ))

    # R2: contradiction CFO support vs Delivery oppose on same future
    for k in "ABC":
        cf, dl = _find(findings, f"CFO-F{k}"), _find(findings, f"DEL-F{k}")
        if cf and dl and cf.stance == "support" and dl.stance == "oppose":
            obs.append(Objection(
                "redteam", "cfo", cf.code, k, "contradiction", "high",
                f"Contradiction on {_fe(k)}: the CFO Agent supports it on savings while the Delivery Agent opposes it "
                f"on delivery evidence. Savings figures exclude the operational cost of the delay the Delivery Agent quantified.",
                f"تناقض حول {_fa(k)}: وكيل المدير المالي يؤيده بسبب الوفورات بينما يعارضه وكيل التسليم بناءً على أدلة "
                f"التسليم. أرقام الوفورات لا تشمل التكلفة التشغيلية للتأخير الذي قاسه وكيل التسليم.",
            ))

    # R3: automation productivity optimism (Future B)
    fb = sim["futures"]["B"]
    sb = {s["parameter"]: s for s in fb["sensitivity"]}
    ap = sb.get("automation_productivity")
    if ap and fb["levers"]["automation_investment"] > 0:
        obs.append(Objection(
            "redteam", "coo", "COO-FB", "B", "optimism", "medium",
            f"Future B relies on automation releasing 1.8 FTE per EGP 1M — an unvalidated prior. At 1.0 FTE/EGP M "
            f"the delay increase becomes +{ap['delay_at_low']:.1f} pts. No pilot data supports the central value.",
            f"المستقبل ب يعتمد على أن الأتمتة تحرر 1.8 موظف لكل مليون جنيه — تقدير غير متحقق منه. عند 1.0 يصبح التأخير "
            f"+{ap['delay_at_low']:.1f} نقطة. لا توجد بيانات تجريبية تدعم القيمة المركزية.",
        ))

    # R4: baseline financial inconsistency undermines all financial claims
    if ctx.validation.has_errors:
        obs.append(Objection(
            "redteam", "cfo", "CFO-02", None, "data_integrity", "high",
            "Every financial projection rests on a dataset that fails its own consistency check (gross margin vs cost base). "
            "Net-benefit figures are only as reliable as that interpretation.",
            "كل التوقعات المالية تعتمد على بيانات فشلت في اختبار الاتساق الخاص بها (الهامش الإجمالي مقابل التكاليف). "
            "أرقام صافي المنفعة موثوقة بقدر هذا التفسير فقط.",
        ))

    # R5: implementation cost overrun skew
    for k in "BC":
        f = sim["futures"][k]
        exp = f["summary"]["one_off_implementation_cost"]["expected"]
        p90 = f["summary"]["one_off_implementation_cost"]["p90"]
        if p90 > exp * 1.2:
            obs.append(Objection(
                "redteam", "cfo", f"CFO-F{k}", k, "optimism", "medium",
                f"{_fe(k)} implementation cost: expected EGP {m(exp)}M but P90 EGP {m(p90)}M. "
                f"Transformation programmes are right-skewed; the business case should be tested at P90.",
                f"تكلفة تنفيذ {_fa(k)}: المتوقع {m(exp)} مليون لكن P90 يبلغ {m(p90)} مليون. برامج التحول تميل للتجاوز؛ "
                f"يجب اختبار الجدوى عند P90.",
            ))

    # R6: target infeasibility vs strategic objective
    ach = {k: sim["futures"][k]["achievable_reduction_pct_at_tolerance"] for k in "ABC"}
    if max(ach.values()) < ctx.controls.cost_reduction_target_pct:
        obs.append(Objection(
            "redteam", "strategy", "STR-01", None, "infeasible_objective", "critical",
            f"The {ctx.controls.cost_reduction_target_pct:.0f}% objective is not reached by any simulated future "
            f"(max {max(ach.values()):.1f}%). Pursuing it unchanged would force violation of a protected constraint.",
            f"هدف {ctx.controls.cost_reduction_target_pct:.0f}% لا يتحقق في أي مستقبل تمت محاكاته (الأقصى "
            f"{max(ach.values()):.1f}%). السعي إليه دون تعديل سيفرض انتهاك قيد محمي.",
        ))

    # R7: hidden dependency — expense freeze cuts training needed for skill match
    fa = sim["futures"]["A"]
    if fa["levers"]["expense_freeze"] >= 0.8 and fa["levers"]["contractor_reduction"] > 0:
        obs.append(Objection(
            "redteam", "cfo", "CFO-FA", "A", "hidden_dependency", "medium",
            "Hidden dependency in Future A: the full expense freeze cuts the training budget that the HR Agent "
            "identified as the lever for raising skill match — which the contractor reduction depends on.",
            "اعتمادية خفية في المستقبل أ: التجميد الكامل للإنفاق يقلص ميزانية التدريب التي حددها وكيل الموارد البشرية "
            "كأداة لرفع توافق المهارات — وهو ما يعتمد عليه خفض المتعاقدين.",
        ))

    # R8: adverse scenario on the safest-looking future
    safest = min("ABC", key=lambda k: sim["futures"][k]["summary"]["max_delay_increase_pct"]["p50"])
    d90 = sim["futures"][safest]["summary"]["max_delay_increase_pct"]["p90"]
    if d90 > acc:
        obs.append(Objection(
            "redteam", "delivery", f"DEL-F{safest}", safest, "adverse_scenario", "medium",
            f"Adverse case for the lowest-delay option ({_fe(safest)}): in the P90 scenario delay still rises "
            f"+{d90:.1f} pts, above the {acc:.1f} pts limit.",
            f"سيناريو سلبي للخيار الأقل تأخيراً ({_fa(safest)}): في سيناريو P90 يرتفع التأخير +{d90:.1f} نقطة متجاوزاً "
            f"الحد {acc:.1f} نقطة.",
        ))
    return obs


def respond(ctx: AgentContext, obs: list[Objection]) -> list[Objection]:
    """Challenged agents answer with the mitigations the model can quantify."""
    sim = ctx.simulation
    assert sim is not None
    for o in obs:
        o.response_by = o.target_agent
        if o.objection_type == "unsupported_assumption":
            o.response_en = ("Conceded in part. The savings estimate stands, but it is conditional on a skills assessment. "
                             "Proposed mitigation: phase the contractor reduction behind a verified skills inventory and retraining.")
            o.response_ar = ("أُقرّ جزئياً. تقدير الوفورات قائم لكنه مشروط بتقييم المهارات. التخفيف المقترح: تقسيم خفض "
                             "المتعاقدين على مراحل بعد التحقق من سجل المهارات وإعادة التأهيل.")
            o.resolution = "partially"
        elif o.objection_type == "contradiction":
            k = o.strategy_key
            loss = sim["futures"][k]["summary"]["delivery_loss_12m"]["p50"]
            o.response_en = (f"Acknowledged. Including the modelled delivery loss (EGP {m(loss)}M over 12 months) the case "
                             f"weakens; the CFO position is revised from 'support' to 'conditional on delivery capacity'.")
            o.response_ar = (f"تم الإقرار. بإضافة خسارة التسليم المتوقعة ({m(loss)} مليون خلال 12 شهراً) تضعف الحجة؛ "
                             f"ويتغير موقف المدير المالي من 'تأييد' إلى 'مشروط بطاقة التسليم'.")
            o.resolution = "partially"
        elif o.objection_type == "optimism" and o.target_agent == "coo":
            o.response_en = ("Valid. Recommend a 6–8 week automation pilot on two processes to measure released capacity "
                             "before committing the full investment and contractor reduction.")
            o.response_ar = ("اعتراض صحيح. نوصي بتجربة أتمتة لمدة 6–8 أسابيع على عمليتين لقياس الطاقة المحررة قبل "
                             "الالتزام بكامل الاستثمار وخفض المتعاقدين.")
            o.resolution = "partially"
        elif o.objection_type == "optimism":
            o.response_en = "Agreed. The dossier reports P90 implementation cost alongside the expected value; approval should use P90."
            o.response_ar = "موافق. يعرض ملف القرار تكلفة التنفيذ عند P90 بجانب القيمة المتوقعة؛ ويجب أن يعتمد القرار على P90."
            o.resolution = "resolved"
        elif o.objection_type == "data_integrity":
            o.response_en = ("Cannot be resolved by analysis. The dataset owner must reconcile gross margin and cost base. "
                             "Governance requires approvers to acknowledge this (GOV-011).")
            o.response_ar = ("لا يمكن حله بالتحليل. يجب على مالك البيانات تسوية الهامش الإجمالي وقاعدة التكاليف. تشترط "
                             "الحوكمة إقرار المعتمدين بذلك (GOV-011).")
            o.resolution = "unresolved"
        elif o.objection_type == "infeasible_objective":
            o.response_en = ("Accepted. The objective conflicts with protected constraints. The orchestrator will present the "
                             "highest achievable reduction and timeline alternatives for an executive decision.")
            o.response_ar = ("مقبول. الهدف يتعارض مع قيود محمية. سيعرض المنسق أعلى نسبة خفض ممكنة وبدائل الإطار الزمني "
                             "لاتخاذ قرار تنفيذي.")
            o.resolution = "unresolved"
        elif o.objection_type == "hidden_dependency":
            o.response_en = "Valid. Ring-fence the training budget (~EGP 1M) from the freeze; savings fall slightly but skill risk drops."
            o.response_ar = "صحيح. يجب استثناء ميزانية التدريب (حوالي مليون جنيه) من التجميد؛ تقل الوفورات قليلاً وتنخفض مخاطر المهارات."
            o.resolution = "partially"
        elif o.objection_type == "adverse_scenario":
            o.response_en = ("Acknowledged. Mitigation: retain a contractor surge clause for critical projects and monitor "
                             "monthly delay against the forecast band.")
            o.response_ar = ("تم الإقرار. التخفيف: الإبقاء على بند استعانة طارئة بالمتعاقدين للمشروعات الحرجة ومراقبة التأخير "
                             "شهرياً مقابل نطاق التوقع.")
            o.resolution = "partially"
    return obs


def governance_findings(ctx: AgentContext, gov: dict[str, dict]) -> list[Finding]:
    """Ethics & Governance agent reports the policy engine's verdicts (it cannot override them)."""
    from .base import Evidence

    out = []
    for k, g in gov.items():
        denied = g["outcome"] == "denied"
        reasons = "; ".join(r["message_en"] for r in g["deny_reasons"]) if denied else ""
        reasons_ar = "؛ ".join(r["message_ar"] for r in g["deny_reasons"]) if denied else ""
        roles = ", ".join(g["required_roles"])
        out.append(Finding(
            "governance", f"GOV-F{k}", "fact", "authority", strategy_key=k,
            stance="oppose" if denied else "conditional", phase="governance",
            text_en=(f"{_fe(k)} is BLOCKED by policy: {reasons}" if denied else
                     f"{_fe(k)} cannot proceed until approved by: {roles}. Agents have no execution authority."),
            text_ar=(f"{_fa(k)} مرفوض بموجب السياسات: {reasons_ar}" if denied else
                     f"{_fa(k)} لا يمكن المضي فيه حتى اعتماده من: {roles}. الوكلاء لا يملكون صلاحية التنفيذ."),
            confidence=1.0,
            evidence=[Evidence("policy", r["code"], r.get("name_en") or r["code"], r["effect"], verified=True)
                      for r in g["policy_results"] if r.get("matched")]))
    peak = {k: ctx.fut(k)["summary"]["peak_utilization_pct"]["p50"] for k in "ABC"}
    over = [k for k, v in peak.items() if v > ctx.controls.max_utilization_pct + 3]
    if over:
        out.append(Finding(
            "governance", "ETH-01", "hypothesis", "ethics",
            f"Ethical concern: {', '.join(_fe(k) for k in over)} push utilisation above the sustainable ceiling, "
            f"shifting contractor workload onto employees (burnout risk) even though no one is terminated.",
            f"مخاوف أخلاقية: {'، '.join(_fa(k) for k in over)} يرفع الاستغلال فوق الحد المستدام وينقل عبء المتعاقدين "
            f"إلى الموظفين (خطر الإرهاق) رغم عدم إنهاء خدمة أحد.",
            0.6, [Evidence("simulation", f"futures.{k}.summary.peak_utilization_pct", "Peak utilisation", f"{peak[k]:.0f}%")
                  for k in over], phase="governance", stance="oppose"))
    return out
