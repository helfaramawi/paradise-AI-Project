def render_xlsx(ctx: dict) -> bytes:
    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill

    lang = ctx["lang"]
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Valuation" if lang == "en" else "التقييم"
    ws.sheet_view.rightToLeft = lang == "ar"
    red = Font(bold=True, color="B42318")
    ws["A1"] = t("draft", lang)
    ws["A1"].font = red
    row = 2
    if ctx["is_demo"]:
        ws["A2"] = t("demo", lang)
        ws["A2"].font = red
        row = 3
    ws.cell(row=row + 1, column=1, value=f"{ctx['project'].name} — {ctx['claim'].ref} — {ctx['type_label']}").font = Font(bold=True, size=13)
    hdr = [t("col_cat", lang), t("col_desc", lang), t("col_qty", lang), t("col_unit", lang), t("col_rate", lang),
           t("col_amount", lang), t("col_source", lang)]
    r0 = row + 3
    for i, h in enumerate(hdr, start=1):
        c = ws.cell(row=r0, column=i, value=h)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="13315C")
    v = ctx["valuation"]
    r = r0
    if v:
        for ln in v.lines:
            r += 1
            ws.cell(row=r, column=1, value=CATEGORIES[ln.category][lang])
            ws.cell(row=r, column=2, value=ln.description)
            ws.cell(row=r, column=3, value=float(ln.quantity))
            ws.cell(row=r, column=4, value=ln.unit or "")
            ws.cell(row=r, column=5, value=float(ln.rate)).number_format = "#,##0.00"
            ws.cell(row=r, column=6, value=f"=ROUND(C{r}*E{r},2)").number_format = "#,##0.00"
            ws.cell(row=r, column=7, value=ln.source_note or "")
        first, last = r0 + 1, r
        r += 2
        labels = [("direct", f"=SUM(F{first}:F{last})"),
                  ("overhead", f"=ROUND(F{r}*{float(v.overhead_pct)}/100,2)"),
                  ("profit", f"=ROUND((F{r}+F{r + 1})*{float(v.profit_pct)}/100,2)"),
                  ("net", f"=F{r}+F{r + 1}+F{r + 2}"),
                  ("vat", f"=ROUND(F{r + 3}*{float(v.vat_rate) if v.vat_applicable else 0}/100,2)"),
                  ("gross", f"=F{r + 3}+F{r + 4}")]
        names = {s["key"]: s[lang] for s in v.totals.get("steps", [])}
        for i, (k, f) in enumerate(labels):
            ws.cell(row=r + i, column=5, value=names.get(k, k)).font = Font(bold=True)
            ws.cell(row=r + i, column=6, value=f).number_format = "#,##0.00"
        r += len(labels) + 1
        ws.cell(row=r, column=1, value=("الافتراضات" if lang == "ar" else "Assumptions")).font = Font(bold=True)
        for a in v.assumptions or []:
            r += 1
            ws.cell(row=r, column=1, value=str(a))
        ws.cell(row=r + 2, column=1, value=("حالة التقييم: " if lang == "ar" else "Valuation status: ") + v.status)
    else:
        ws.cell(row=r0 + 1, column=1, value=t("no_val", lang))
    for col, w in zip("ABCDEFG", (24, 60, 10, 8, 14, 16, 40), strict=True):
        ws.column_dimensions[col].width = w
    for rr in ws.iter_rows():
        for c in rr:
            c.alignment = Alignment(wrap_text=True, vertical="top", horizontal="right" if lang == "ar" else None)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def render(db: Session, claim: Claim, kind: str, fmt: str, lang: str) -> tuple[bytes, str, str]:
    ctx = build_context(db, claim, lang)
    if fmt == "xlsx":
        return render_xlsx(ctx), "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "xlsx"
    if fmt == "pdf":
        return render_pdf(ctx, kind), "application/pdf", "pdf"
    return render_docx(ctx, kind), "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "docx"
