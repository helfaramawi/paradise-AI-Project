def render_docx(ctx: dict, kind: str) -> bytes:
    import docx
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    lang = ctx["lang"]
    rtl = lang == "ar"
    d = docx.Document()
    style = d.styles["Normal"]
    style.font.name = "Arial"
    style.font.size = Pt(10.5)
    style.element.rPr.rFonts.set(qn("w:cs"), "Arial")

    def para(text: str, *, bold=False, size=None, color=None, italic=False, heading=False):
        p = d.add_paragraph()
        if rtl:
            ppr = p._p.get_or_add_pPr()
            bidi = OxmlElement("w:bidi")
            bidi.set(qn("w:val"), "1")
            ppr.append(bidi)
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        r = p.add_run(text)
        r.bold, r.italic = bold, italic
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = RGBColor.from_string(color)
        if rtl:
            rpr = r._r.get_or_add_rPr()
            rtl_el = OxmlElement("w:rtl")
            rtl_el.set(qn("w:val"), "1")
            rpr.append(rtl_el)
            if bold:
                rpr.append(OxmlElement("w:bCs"))
        if heading:
            p.paragraph_format.space_before = Pt(12)
        return p

    para(t("draft", lang), bold=True, color="B42318", size=9)
    if ctx["is_demo"]:
        para(t("demo", lang), bold=True, color="B54708", size=9)
    claim, project, org = ctx["claim"], ctx["project"], ctx["org"]
    for k, v in (("from", org.name_ar if rtl and org.name_ar else org.name),
                 ("to", project.engineer_name or project.employer_name or t("verify", lang)),
                 ("project", project.name_ar if rtl and project.name_ar else project.name),
                 ("ref", f"{project.code}/{claim.ref}"), ("date", date.today().isoformat())):
        para(f"{t(k, lang)}: {v}")
    para(f"{t('subject', lang)}: {_subject(ctx, kind)}", bold=True, size=13, color="0B2545")
    for heading, blocks in _sections(ctx, kind):
        if heading:
            para(heading, bold=True, size=12, color="13315C", heading=True)
        for b in blocks:
            if b[0] == "p":
                para(b[1])
            elif b[0] == "quote":
                para(b[1], italic=True, size=9.5, color="475467")
            elif b[0] == "table":
                header, rows = b[1], b[2]
                tbl = d.add_table(rows=1, cols=len(header))
                tbl.style = "Light Grid Accent 1"
                if rtl:
                    tbl_pr = tbl._tbl.tblPr
                    bv = OxmlElement("w:bidiVisual")
                    bv.set(qn("w:val"), "1")
                    tbl_pr.append(bv)
                for i, h in enumerate(header):
                    tbl.rows[0].cells[i].text = h
                for r in rows:
                    cells = tbl.add_row().cells
                    for i, v in enumerate(r):
                        cells[i].text = str(v)
    para("")
    para("— " + ("أُعد بواسطة منصة حقّك – Paradise AI Solutions" if rtl else "Prepared with HAQQ — Paradise AI Solutions"),
         size=8, color="667085")
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


