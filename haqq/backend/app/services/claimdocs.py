def t(key: str, lang: str) -> str:
    en, ar = T[key]
    return ar if lang == "ar" else en


def money(v, cur="EGP") -> str:
    if v is None:
        return "—"
    return f"{Decimal(v):,.2f} {cur}"


# ------------------------------------------------------------------ context


def build_context(db: Session, claim: Claim, lang: str) -> dict:
    org = db.get(Organization, claim.org_id)
    project = db.get(Project, claim.project_id)
    ent = db.get(Entitlement, claim.entitlement_id) if claim.entitlement_id else None
    ev = db.get(ProjectEvent, ent.event_id) if ent else None
    clauses = []
    if ent:
        for cid in [ent.primary_clause_id, *(ent.related_clause_ids or [])[:3]]:
            c = db.get(Clause, cid) if cid else None
            if c:
                d = db.get(Document, c.document_id)
                clauses.append({"number": c.clause_number, "title": c.title, "text": c.text[:1500],
                                "document": d.title if d else "", "page": c.page_start,
                                "verified": c.verification_status == "verified", "primary": cid == ent.primary_clause_id})
    chronology = []
    if ev:
        chronology.append({"date": ev.event_date, "text": f"{ev.ref}: {ev.title}", "source": "Event register"})
        docs = db.execute(select(Document).join(EventDocument, EventDocument.document_id == Document.id)
                          .where(EventDocument.event_id == ev.id, EventDocument.confirmed.is_(True))).scalars().all()
        for d in docs:
            chronology.append({"date": d.doc_date, "text": f"{d.title} ({d.doc_type})", "source": d.filename})
    chronology.sort(key=lambda r: (r["date"] or date.max))
    valuation = db.execute(select(Valuation).where(Valuation.entitlement_id == ent.id)).scalar_one_or_none() if ent else None
    tinfo = ENTITLEMENT_TYPES.get(ent.entitlement_type, {}) if ent else {}
    return {"lang": lang, "org": org, "project": project, "claim": claim, "ent": ent, "event": ev, "clauses": clauses,
            "chronology": chronology, "valuation": valuation, "type_label": tinfo.get(lang, claim.claim_type),
            "notice": (ent.notice or {}).get("notice") if ent else None, "is_demo": project.is_demo or claim.is_demo}


def _subject(ctx: dict, kind: str) -> str:
    lang, ent = ctx["lang"], ctx["ent"]
    etype = ent.entitlement_type if ent else ""
    if kind == "notice":
        if etype in ("extension_of_time", "prolongation_cost"):
            return "إخطار بتأخير ومطالبة محتملة" if lang == "ar" else "Notice of Delay and Potential Claim"
        if etype == "variation_payment":
            return "إخطار بمطالبة عن أعمال إضافية / تغيير" if lang == "ar" else "Notice of Claim — Variation / Additional Works"
        return "إخطار بمطالبة" if lang == "ar" else "Notice of Claim"
    return (f"مطالبة: {ctx['type_label']}" if lang == "ar" else f"Claim Submission: {ctx['type_label']}")


def _sections(ctx: dict, kind: str) -> list[tuple[str, list]]:
    """Format-independent content: list of (heading, blocks). Block = ('p', text) | ('table', header, rows)."""
    lang, claim, ent, ev, project = ctx["lang"], ctx["claim"], ctx["ent"], ctx["event"], ctx["project"]
    V = t("verify", lang)
    primary = next((c for c in ctx["clauses"] if c["primary"]), None)
    notice = ctx["notice"] or {}
    secs: list[tuple[str, list]] = []
    if kind == "notice":
        body = []
        if lang == "ar":
            body.append(("p", f"بالإشارة إلى العقد الخاص بمشروع {project.name_ar or project.name}، نتشرف بإخطاركم بوقوع "
                              f"الحدث التالي: {ev.title if ev else claim.title} بتاريخ {ev.event_date if ev else V}."))
            if primary:
                body.append(("p", f"ويُقدم هذا الإخطار وفقًا للبند {primary['number']} ({primary['title']}) من "
                                  f"{primary['document']}، ص {primary['page']}" + ("" if primary["verified"] else f" {V}") + "."))
            else:
                body.append(("p", f"البند التعاقدي الذي يستند إليه هذا الإخطار: {V}"))
            body.append(("p", "يرى المقاول أن هذا الحدث قد يترتب عليه استحقاق تعاقدي، وسيقوم بتقديم التفاصيل المؤيدة "
                              "والتقييم المالي و/أو الزمني في الموعد التعاقدي."))
        else:
            body.append(("p", f"With reference to the Contract for {project.name}, we hereby give notice of the following "
                              f"event: {ev.title if ev else claim.title}, which occurred on {ev.event_date if ev else V}."))
            if primary:
                body.append(("p", f"This notice is given pursuant to Clause {primary['number']} ({primary['title']}) of "
                                  f"{primary['document']}, p.{primary['page']}" + ("" if primary["verified"] else f" {V}") + "."))
            else:
                body.append(("p", f"Contractual basis for this notice: {V}"))
            body.append(("p", "The Contractor considers that this event may give rise to a contractual entitlement and "
                              "will submit supporting particulars and its financial and/or time assessment within the "
                              "period required by the Contract."))
        if notice.get("due_date"):
            body.append(("p", (f"موعد الإخطار المحسوب: {notice['due_date']} ({notice['certainty']}) {V}" if lang == "ar"
                               else f"Computed notice deadline: {notice['due_date']} ({notice['certainty']}) {V}")))
        body.append(("p", t("reservation", lang)))
        secs.append(("", body))
        return secs

    # full package
    summ = []
    if ent:
        fin = money(ent.financial_impact, ent.currency) if ent.financial_impact is not None else t("no_val", lang)
        if lang == "ar":
            summ.append(("p", f"تتعلق هذه المطالبة بـ {ctx['type_label']} الناشئ عن الحدث {ev.ref}: {ev.title}. "
                              f"القيمة المقدرة: {fin}. الأثر الزمني: {ent.time_impact_days or '—'} يوم. "
                              f"حالة النتيجة: {LABELS_STATUS[ent.status]['ar']}؛ درجة الثقة {int(ent.confidence * 100)}%."))
        else:
            summ.append(("p", f"This claim concerns {ctx['type_label']} arising from event {ev.ref}: {ev.title}. "
                              f"Estimated value: {fin}. Time impact: {ent.time_impact_days or '—'} days. Finding status: "
                              f"{LABELS_STATUS[ent.status]['en']}; confidence {int(ent.confidence * 100)}%."))
        if ev:
            summ.append(("p", ev.description))
    secs.append((t("summary", lang), summ))
    basis = []
    for c in ctx["clauses"]:
        basis.append(("p", f"{t('clause', lang)} {c['number']} — {c['title']} ({c['document']}, {t('page', lang)} {c['page']})"
                           + ("" if c["verified"] else f" {V}")))
        basis.append(("quote", c["text"][:900]))
    if ent and ent.exclusions:
        for ex in ent.exclusions:
            basis.append(("p", ("⚠ استثناء محتمل: " if lang == "ar" else "⚠ Potential exclusion: ") + ex["text"]))
    secs.append((t("basis", lang), basis or [("p", f"{t('none', lang)} {V}")]))
    secs.append((t("chronology", lang), [("table", [t("col_date", lang), t("col_desc", lang), t("col_source", lang)],
                                          [[str(r["date"] or V), r["text"], r["source"]] for r in ctx["chronology"]])]))
    ev_rows = []
    if ent:
        for a in ent.evidence_available:
            for s in a.get("sources", []):
                ev_rows.append([a[lang] if lang in a else a["en"], s.get("document_title", ""), s.get("doc_type", "") or "",
                                str(s.get("doc_date") or "—"), str(s.get("page", ""))])
    secs.append((t("evidence", lang), [("table", [t("col_req", lang), t("col_doc", lang), t("col_type", lang),
                                                  t("col_date", lang), t("col_page", lang)], ev_rows)]
                 if ev_rows else [("p", t("none", lang))]))
    miss = [("p", f"• {m[lang] if lang in m else m['en']}" + (" (جوهري)" if lang == "ar" and m["critical"] else
                                                               " (critical)" if m["critical"] else ""))
            for m in (ent.evidence_missing if ent else [])]
    secs.append((t("missing", lang), miss or [("p", t("none", lang))]))
    v = ctx["valuation"]
    if v and v.totals.get("lines"):
        rows = [[CATEGORIES[ln["category"]][lang], ln["description"], ln["quantity"], ln["unit"] or "", ln["rate"],
                 ln["amount"]] for ln in v.totals["lines"]]
        fin_blocks = [("table", [t("col_cat", lang), t("col_desc", lang), t("col_qty", lang), t("col_unit", lang),
                                 t("col_rate", lang), t("col_amount", lang)], rows)]
        for st in v.totals["steps"]:
            fin_blocks.append(("p", f"{st[lang]}: {st['formula']} → {money(st['value'], v.currency)}"))
        if v.status != "verified":
            fin_blocks.append(("p", ("التقييم لم يُعتمد بعد " if lang == "ar" else "Valuation not yet verified ") + V))
        for a in v.assumptions or []:
            fin_blocks.append(("p", ("افتراض: " if lang == "ar" else "Assumption: ") + str(a)))
    else:
        fin_blocks = [("p", t("no_val", lang))]
    secs.append((t("financial", lang), fin_blocks))
    secs.append((t("time", lang), [("p", (f"الأثر الزمني المقدر: {ent.time_impact_days} يوم. يتطلب تحليل تأخير على المسار الحرج. {V}"
                                          if lang == "ar" else
                                          f"Estimated time impact: {ent.time_impact_days} days. Requires a critical-path delay analysis. {V}")
                                         if ent and ent.time_impact_days else t("none", lang))]))
    nb = []
    if notice.get("required"):
        nb.append(("p", (f"المهلة: {notice['stated']} ({notice['day_type']}) — من: {notice.get('trigger_wording') or '—'} — "
                         f"الاستحقاق: {notice['due_date']} ({notice['certainty']}) — الحالة: {notice['status']}") if lang == "ar"
                  else (f"Period: {notice['stated']} ({notice['day_type']}) — from: {notice.get('trigger_wording') or '—'} — "
                        f"due: {notice['due_date']} ({notice['certainty']}) — status: {notice['status']}")))
        for n in notice.get("notes", []):
            nb.append(("p", f"• {n[lang]}"))
    else:
        nb.append(("p", (f"لم يُحدد متطلب إخطار في المستندات المحللة. {V}" if lang == "ar"
                         else f"No notice requirement identified in the analysed documents. {V}")))
    secs.append((t("notice", lang), nb))
    asum = [("p", f"• {a.get(lang, a.get('en'))}") for a in (ent.assumptions if ent else [])]
    secs.append((t("assumptions", lang), asum or [("p", t("none", lang))]))
    rev = ent.review_status if ent else "—"
    secs.append((t("review", lang), [("p", (f"مرحلة المطالبة: {claim.stage} — مراجعة النتيجة: {rev}" if lang == "ar"
                                            else f"Claim stage: {claim.stage} — finding review: {rev}"))]))
    return secs


