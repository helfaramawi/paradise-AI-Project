def render_pdf(ctx: dict, kind: str) -> bytes:
    from xml.sax.saxutils import escape

    import arabic_reshaper
    from bidi.algorithm import get_display
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT, TA_RIGHT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    if "HaqqSans" not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont("HaqqSans", str(FONT_DIR / "DejaVuSans.ttf")))
        pdfmetrics.registerFont(TTFont("HaqqSans-Bold", str(FONT_DIR / "DejaVuSans-Bold.ttf")))
    lang = ctx["lang"]
    rtl = lang == "ar"

    def tx(s: str) -> str:
        s = escape(str(s))
        return get_display(arabic_reshaper.reshape(s)) if rtl else s

    align = TA_RIGHT if rtl else TA_LEFT
    base = ParagraphStyle("b", fontName="HaqqSans", fontSize=9.5, leading=14, alignment=align)
    bold = ParagraphStyle("h", parent=base, fontName="HaqqSans-Bold", fontSize=11.5, leading=16,
                          textColor=colors.HexColor("#13315C"), spaceBefore=8)
    title = ParagraphStyle("t", parent=bold, fontSize=14, textColor=colors.HexColor("#0B2545"))
    warn = ParagraphStyle("w", parent=base, fontName="HaqqSans-Bold", fontSize=8, textColor=colors.HexColor("#B42318"))
    quote = ParagraphStyle("q", parent=base, fontSize=8.5, textColor=colors.HexColor("#475467"), leftIndent=8, rightIndent=8)
    story = [Paragraph(tx(t("draft", lang)), warn)]
    if ctx["is_demo"]:
        story.append(Paragraph(tx(t("demo", lang)), warn))
    claim, project, org = ctx["claim"], ctx["project"], ctx["org"]
    for k, v in (("from", org.name_ar if rtl and org.name_ar else org.name),
                 ("to", project.engineer_name or project.employer_name or t("verify", lang)),
                 ("project", project.name_ar if rtl and project.name_ar else project.name),
                 ("ref", f"{project.code}/{claim.ref}"), ("date", date.today().isoformat())):
        story.append(Paragraph(tx(f"{t(k, lang)}: {v}"), base))
    story += [Spacer(1, 4), Paragraph(tx(f"{t('subject', lang)}: {_subject(ctx, kind)}"), title), Spacer(1, 4)]
    cell = ParagraphStyle("c", parent=base, fontSize=7.5, leading=10)
    for heading, blocks in _sections(ctx, kind):
        if heading:
            story.append(Paragraph(tx(heading), bold))
        for b in blocks:
            if b[0] == "p":
                story.append(Paragraph(tx(b[1]), base))
            elif b[0] == "quote":
                story.append(Paragraph(tx(b[1]), quote))
            elif b[0] == "table":
                header, rows = b[1], b[2]
                data = [[Paragraph(tx(h), cell) for h in header]] + [[Paragraph(tx(v), cell) for v in r] for r in rows]
                if rtl:
                    data = [list(reversed(r)) for r in data]
                tb = Table(data, repeatRows=1, hAlign="RIGHT" if rtl else "LEFT")
                tb.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D0D5DD")),
                                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAF0F8")),
                                        ("VALIGN", (0, 0), (-1, -1), "TOP")]))
                story.append(tb)
        story.append(Spacer(1, 3))
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
                      title=_subject(ctx, kind), author="HAQQ").build(story)
    return buf.getvalue()


