function cell(content, width, o = {}) {
  const items = Array.isArray(content) ? content : [content];
  return new TableCell({
    width: { size: width, type: WidthType.DXA }, borders, columnSpan: o.span,
    verticalAlign: o.vAlign || VerticalAlign.CENTER,
    shading: o.fill ? { type: ShadingType.CLEAR, color: "auto", fill: o.fill } : undefined,
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    children: items.map((t) => new Paragraph({
      bidirectional: true, alignment: o.align || AlignmentType.START,
      spacing: { before: 10, after: 10, line: 270 },
      children: runs(t, { size: o.size || 19, bold: o.bold, color: o.color }),
    })),
  });
}
function table(headers, rows, widths, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const trs = [];
  if (headers) trs.push(new TableRow({
    tableHeader: true, cantSplit: true,
    children: headers.map((h, i) => cell(h, widths[i], { fill: NAVY, color: "FFFFFF", bold: true, size: 19 })),
  }));
  rows.forEach((r, ri) => trs.push(new TableRow({
    cantSplit: true,
    children: r.map((c, i) => cell(c, widths[i], {
      fill: (o.firstColFill && i === 0) ? LIGHT : (ri % 2 ? GREY : undefined),
      bold: o.firstColBold && i === 0, align: (o.center && o.center.includes(i)) ? AlignmentType.CENTER : undefined,
    })),
  })));
  return [new Table({
    visuallyRightToLeft: true, width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    layout: TableLayoutType.FIXED, rows: trs,
  }), new Paragraph({ spacing: { before: 0, after: 120 }, children: [] })];
}
function callout(title, text, fill = LIGHT) {
  const c = new TableCell({
    width: { size: W, type: WidthType.DXA }, shading: { type: ShadingType.CLEAR, color: "auto", fill },
    borders: { top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" }, bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" }, right: { style: BorderStyle.SINGLE, size: 36, color: BLUE } },
    margins: { top: 120, bottom: 120, left: 200, right: 200 },
    children: [
      ...(title ? [new Paragraph({ bidirectional: true, spacing: { after: 60 }, children: runs(title, { bold: true, color: NAVY, size: 23 }) })] : []),
      ...(Array.isArray(text) ? text : [text]).map((t) => new Paragraph({ bidirectional: true, alignment: AlignmentType.BOTH, spacing: { after: 40, line: 290 }, children: runs(t) })),
    ],
  });
  return [new Table({ visuallyRightToLeft: true, width: { size: W, type: WidthType.DXA }, columnWidths: [W], rows: [new TableRow({ cantSplit: true, children: [c] })] }),
    new Paragraph({ spacing: { after: 120 }, children: [] })];
}

