// ---------- text helpers ----------
function runs(text, o = {}) {
  // supports **bold** inline markup
  const parts = String(text).split(/(\*\*[^*]+\*\*)/g).filter(Boolean);
  return parts.map((p) => {
    const b = p.startsWith("**") && p.endsWith("**");
    const t = b ? p.slice(2, -2) : p;
    const bold = o.bold || b;
    return new TextRun({
      text: t, rightToLeft: true, bold, boldComplexScript: bold, italics: o.italics, italicsComplexScript: o.italics,
      font: { ascii: FONT, hAnsi: FONT, cs: FONT, eastAsia: FONT },
      size: o.size || 22, sizeComplexScript: o.size || 22, color: o.color || "1A1A1A",
    });
  });
}
const P = (text, o = {}) => new Paragraph({
  bidirectional: true, alignment: o.align || AlignmentType.BOTH,
  spacing: { before: o.before ?? 60, after: o.after ?? 100, line: o.line || 300 },
  keepNext: o.keepNext, children: runs(text, o),
});
